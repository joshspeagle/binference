def f(x: float) -> str:
    return f"{x:.2f}".rstrip("0").rstrip(".")


def svg(body: str, label: str, cls: str = "mark") -> str:
    return (
        f'<svg class="{cls}" viewBox="0 0 64 64" role="img" aria-label="{html.escape(label)}">'
        f"{body}</svg>"
    )


