def fonts_link():
    weights = {}
    for d in DIRS:
        weights.setdefault(d["display"], set()).add(d["dweight"])
        weights.setdefault(d["body"], set()).update({400, 700} if d["body"] == "Atkinson Hyperlegible" else {400, 600})
    weights["IBM Plex Sans"] = {400, 600}
    fams = [f"family={k.replace(' ', '+')}:wght@{';'.join(map(str, sorted(v)))}" for k, v in weights.items()]
    fams.append("family=Literata:opsz,wght@7..72,600")
    return "https://fonts.googleapis.com/css2?" + "&".join(fams) + "&display=swap"


