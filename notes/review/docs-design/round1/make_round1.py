def mark_drop(c, small):
    """A: the letter b drawn as histogram bins around a round counter that holds one sample."""
    base, x0 = 58.0, 7.0
    sw, w, gap, nb = (9.5, 8.0, 2.2, 4) if small else (8.5, 3.9, 1.3, 9)
    R = 17.0 if small else 16.5  # outer radius of the bowl
    r = 7.6 if small else 7.4    # radius of the counter
    bx0 = x0 + sw + gap
    span = nb * (w + gap) - gap
    cx, cy = bx0 + span / 2 - 1.0, base - R
    parts = [f'<rect x="{f(x0)}" y="4" width="{f(sw)}" height="{f(base - 4)}" fill="{c["main"]}"/>']
    for k in range(nb):
        x = bx0 + k * (w + gap)
        dx = x + w / 2 - cx
        top = cy - math.sqrt(max(R * R - dx * dx, 0)) if abs(dx) < R else cy
        if abs(dx) < r:  # cut the counter out of this bin
            half = math.sqrt(r * r - dx * dx)
            parts.append(f'<rect x="{f(x)}" y="{f(top)}" width="{f(w)}" height="{f(cy - half - top)}" fill="{c["main"]}"/>')
            parts.append(f'<rect x="{f(x)}" y="{f(cy + half)}" width="{f(w)}" height="{f(base - cy - half)}" fill="{c["main"]}"/>')
        else:
            parts.append(f'<rect x="{f(x)}" y="{f(top)}" width="{f(w)}" height="{f(base - top)}" fill="{c["main"]}"/>')
    parts.append(f'<circle cx="{f(cx)}" cy="{f(cy)}" r="{3.6 if small else 3.2}" fill="{c["accent"]}"/>')
    return "".join(parts)


def mark_die(c, small):
    """B: a die whose pips are stacked into a histogram."""
    if small:
        cols, xs, rows, r = [1, 3, 2], [20, 32, 44], [46, 34, 22], 5.0
        rot = ""
    else:
        cols, xs, rows, r = [1, 3, 4, 2], [17, 27, 37, 47], [47, 37, 27, 17], 3.7
        rot = ' transform="rotate(-7 32 32)"'
    pips = "".join(
        f'<circle cx="{x}" cy="{rows[j]}" r="{r}" fill="{c["paper"]}"/>'
        for x, n in zip(xs, cols)
        for j in range(n)
    )
    return f'<g{rot}><rect x="5" y="5" width="54" height="54" rx="13" fill="{c["main"]}"/>{pips}</g>'


def mark_simplex(c, small):
    """C: the probability simplex cut into bins, shaded by a posterior density."""
    top, bl, br = np.array([32, 5.0]), np.array([5, 52.0]), np.array([59, 52.0])
    n = 3 if small else 5
    mode = np.array([0.22, 0.5, 0.28])  # weights on (top, bl, br)

    def pt(i, j):  # i steps toward bl, j toward br, from top
        return top + (bl - top) * i / n + (br - top) * j / n

    cells = []
    for i in range(n):
        for j in range(n - i):
            tri = [pt(i, j), pt(i + 1, j), pt(i, j + 1)]
            cells.append(tri)
            if i + j < n - 1:
                cells.append([pt(i + 1, j), pt(i + 1, j + 1), pt(i, j + 1)])
    ramp = c["ramp"]
    out = []
    for tri in cells:
        cen = sum(tri) / 3
        # barycentric weights of the centre
        lam = np.linalg.solve(np.array([[*top, 1], [*bl, 1], [*br, 1]]).T, np.array([*cen, 1]))
        d = np.sqrt(((lam - mode) ** 2).sum())
        level = min(int(d / 0.13), len(ramp) - 1)
        pts = " ".join(f"{f(p[0])},{f(p[1])}" for p in tri)
        out.append(
            f'<polygon points="{pts}" fill="{ramp[level]}" stroke="{c["bg"]}" '
            f'stroke-width="{1.6 if small else 1.1}" stroke-linejoin="round"/>'
        )
    m = top * mode[0] + bl * mode[1] + br * mode[2]
    out.append(
        f'<circle cx="{f(m[0])}" cy="{f(m[1])}" r="{4.2 if small else 3.2}" fill="{c["accent"]}" '
        f'stroke="{c["bg"]}" stroke-width="1.4"/>'
    )
    return "".join(out)


def _step_path(h, x0, x1, base):
    k = len(h)
    w = (x1 - x0) / k
    d = f"M{f(x0)} {f(base)}"
    for i, hi in enumerate(h):
        d += f"V{f(base - hi)}H{f(x0 + (i + 1) * w)}"
    return d + f"V{f(base)}"


def mark_draws(c, small):
    """D: a histogram drawn as many posterior draws, with their mean."""
    rng = np.random.default_rng(7)
    shape = np.array([0.05, 0.15, 0.26, 0.3, 0.2, 0.1, 0.04]) if not small else np.array(
        [0.12, 0.3, 0.36, 0.22]
    )
    shape = shape / shape.max() * 42
    nd, sw, op = (3, 2.6, 0.5) if small else (9, 1.4, 0.4)
    out = [
        f'<line x1="5" y1="57" x2="59" y2="57" stroke="{c["ink"]}" stroke-width="{2.6 if small else 2}"/>'
    ]
    for _ in range(nd):
        h = shape * np.exp(rng.normal(0, 0.13, shape.size))
        out.append(
            f'<path d="{_step_path(np.minimum(h, 50), 7, 57, 57)}" fill="none" stroke="{c["main"]}" '
            f'stroke-width="{sw}" opacity="{op}" stroke-linejoin="round"/>'
        )
    out.append(
        f'<path d="{_step_path(shape, 7, 57, 57)}" fill="none" stroke="{c["accent"]}" '
        f'stroke-width="{3.6 if small else 2.6}" stroke-linejoin="round"/>'
    )
    return "".join(out)


def _wedge(cx, cy, r, a0, a1):
    p0 = (cx + r * math.cos(a0), cy + r * math.sin(a0))
    p1 = (cx + r * math.cos(a1), cy + r * math.sin(a1))
    large = 1 if (a1 - a0) % (2 * math.pi) > math.pi else 0
    return (
        f"M{f(cx)} {f(cy)}L{f(p0[0])} {f(p0[1])}"
        f"A{f(r)} {f(r)} 0 {large} 1 {f(p1[0])} {f(p1[1])}Z"
    )


def mark_split(c, small):
    """E: one uncertain object splits its probability between two bins."""
    p = 0.64
    cx, cy, r = 32, 17, 11.5
    split = math.pi / 2 + 0.25  # split line tilted
    a_left0, a_left1 = split, split + 2 * math.pi * p
    gapv = 1.8
    mid_l = (a_left0 + a_left1) / 2
    mid_r = mid_l + math.pi
    left = _wedge(cx + gapv * math.cos(mid_l), cy + gapv * math.sin(mid_l), r, a_left0, a_left1)
    right = _wedge(cx + gapv * math.cos(mid_r), cy + gapv * math.sin(mid_r), r, a_left1, a_left0 + 2 * math.pi)
    sw = 4.2 if small else 3.4
    cup = lambda x: (  # noqa: E731
        f'<path d="M{x} 38V53Q{x} 58 {x + 5} 58H{x + 15}Q{x + 20} 58 {x + 20} 53V38" '
        f'fill="none" stroke="{c["ink"]}" stroke-width="{sw}" stroke-linecap="round"/>'
    )
    fill = lambda x, frac, col: (  # noqa: E731
        f'<rect x="{x + sw / 2 + 0.6}" y="{f(56.5 - 16 * frac)}" width="{f(20 - sw - 1.2)}" '
        f'height="{f(16 * frac)}" rx="2.5" fill="{col}"/>'
    )
    return (
        f'<path d="{left}" fill="{c["main"]}"/><path d="{right}" fill="{c["accent"]}"/>'
        + fill(7, p, c["main"]) + fill(37, 1 - p, c["accent"]) + cup(7) + cup(37)
    )


def mark_tittle(c, small):
    """F: the letter i whose dot is a measurement with an error bar."""
    sw = 3.4 if small else 2.6
    bar = (
        f'<line x1="32" y1="{5 if not small else 7}" x2="32" y2="{25 if not small else 23}" '
        f'stroke="{c["accent"]}" stroke-width="{sw}" stroke-linecap="round"/>'
    )
    caps = "" if small else (
        f'<line x1="27.5" y1="5" x2="36.5" y2="5" stroke="{c["accent"]}" stroke-width="{sw}" stroke-linecap="round"/>'
        f'<line x1="27.5" y1="25" x2="36.5" y2="25" stroke="{c["accent"]}" stroke-width="{sw}" stroke-linecap="round"/>'
    )
    return (
        f'<rect x="26" y="31" width="12" height="28" fill="{c["ink"]}"/>'
        + bar + caps
        + f'<circle cx="32" cy="15" r="{7 if small else 6}" fill="{c["accent"]}"/>'
    )


def mark_shrink(c, small):
    """G: noisy measurements pulled onto the population they share."""
    def curve_y(x):
        return 54 - 36 * math.exp(-((x - 32) ** 2) / (2 * 11**2))

    xs = np.linspace(5, 59, 40)
    d = "M" + " L".join(f"{f(x)} {f(curve_y(x))}" for x in xs)
    out = [
        f'<path d="{d}" fill="none" stroke="{c["main"]}" stroke-width="{4 if small else 3}" stroke-linecap="round"/>'
    ]
    pts = [(14, 30), (26, 42), (40, 11), (51, 32)] if not small else [(20, 22), (46, 18)]
    for x, y0 in pts:
        y1 = curve_y(x) + (y0 - curve_y(x)) * 0.12
        if not small:
            out.append(
                f'<line x1="{x}" y1="{y0 - 6}" x2="{x}" y2="{y0 + 6}" stroke="{c["muted"]}" stroke-width="1.4"/>'
                f'<circle cx="{x}" cy="{y0}" r="2.8" fill="{c["bg"]}" stroke="{c["muted"]}" stroke-width="1.4"/>'
                f'<line x1="{x}" y1="{f(y0 + (3.2 if y1 > y0 else -3.2))}" x2="{x}" '
                f'y2="{f(y1 - (4 if y1 > y0 else -4))}" stroke="{c["muted"]}" stroke-width="1" opacity=".8"/>'
            )
        out.append(
            f'<circle cx="{x}" cy="{f(y1)}" r="{5 if small else 3.6}" fill="{c["accent"]}" '
            f'stroke="{c["bg"]}" stroke-width="1.4"/>'
        )
    return "".join(out)


