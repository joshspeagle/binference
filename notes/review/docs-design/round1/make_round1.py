def tokens(d, which):
    vals = d[which]
    return ";".join(f"--{k}:{v}" for k, v in vals.items())


def wordmark(d):
    if d["key"] == "tittle":
        # dotless i with the measurement drawn over it
        tit = mark_tittle_dot()
        return f'<span class="wm">b<span class="ti">ı{tit}</span>nference</span>'
    return '<span class="wm">binference</span>'


def mark_tittle_dot():
    """The error-bar dot that sits over a dotless i in the wordmark (24 x 34 units)."""
    st = 'stroke="var(--accent)" stroke-width="3.2" stroke-linecap="round"'
    return (
        '<svg class="tit" viewBox="0 0 24 34" aria-hidden="true">'
        f'<line x1="12" y1="2" x2="12" y2="30" {st}/><line x1="5" y1="2" x2="19" y2="2" {st}/>'
        f'<line x1="5" y1="30" x2="19" y2="30" {st}/><circle cx="12" cy="20" r="7" fill="var(--accent)"/></svg>'
    )


