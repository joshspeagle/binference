def _bowl(nb, x0, sw, w, gap, base, R):
    """Bin edges and outer heights of a b: the stem, then bins tracing a round bowl."""
    bx0 = x0 + sw + gap
    span = nb * (w + gap) - gap
    cx, cy = bx0 + span / 2 - 1.0, base - R
    bins = []
    for k in range(nb):
        x = bx0 + k * (w + gap)
        dx = x + w / 2 - cx
        top = cy - math.sqrt(max(R * R - dx * dx, 0)) if abs(dx) < R else cy
        bins.append((x, base - top, dx))
    return bins, cx, cy


def mark_interval(c, small):
    """A+D: the histogram b, each bin drawn to its lower bound with a pale band up to its upper."""
    base, x0 = 58.0, 7.0
    sw, w, gap, nb = (9.5, 8.0, 2.2, 4) if small else (8.5, 3.9, 1.3, 9)
    R, r = (17.0, 7.6) if small else (16.5, 7.4)
    bins, cx, cy = _bowl(nb, x0, sw, w, gap, base, R)
    def band(h):  # a counting error: the band grows as the square root of the height
        return 1.1 * math.sqrt(h)

    def column(x, width, h, cut=None):
        top = base - h
        lo = top + band(h)
        out = [f'<rect x="{f(x)}" y="{f(top)}" width="{f(width)}" height="{f(lo - top)}" fill="{c["main"]}" opacity=".38"/>']
        if cut is None:
            out.append(f'<rect x="{f(x)}" y="{f(lo)}" width="{f(width)}" height="{f(base - lo)}" fill="{c["main"]}"/>')
        else:
            a, b = cut
            if a > lo:
                out.append(f'<rect x="{f(x)}" y="{f(lo)}" width="{f(width)}" height="{f(a - lo)}" fill="{c["main"]}"/>')
            out.append(f'<rect x="{f(x)}" y="{f(b)}" width="{f(width)}" height="{f(base - b)}" fill="{c["main"]}"/>')
        return "".join(out)

    parts = [column(x0, sw, base - 4)]
    for x, h, dx in bins:
        cut = None
        if abs(dx) < r:
            half = math.sqrt(r * r - dx * dx)
            cut = (cy - half, cy + half)
        parts.append(column(x, w, h, cut))
    parts.append(f'<circle cx="{f(cx)}" cy="{f(cy)}" r="{3.6 if small else 3.2}" fill="{c["accent"]}"/>')
    return "".join(parts)


def mark_pips(c, small):
    """A+B: a die tile whose pips are stacked into histogram columns that spell a b."""
    rows = ["X...", "X...", "XXX.", "X..X", "XXXX"]
    if small:
        rows = ["X..", "XX.", "X.X", "XXX"]
        xs, ys, r = [18, 32, 46], [16, 27, 38, 49], 5.0
    else:
        xs, ys, r = [17.5, 27, 36.5, 46], [13, 22.5, 32, 41.5, 51], 3.7
    pips = "".join(
        f'<circle cx="{xs[j]}" cy="{ys[i]}" r="{r}" fill="{c["paper"]}"/>'
        for i, row in enumerate(rows)
        for j, ch in enumerate(row)
        if ch == "X"
    )
    if small:
        sample = f'<circle cx="{xs[1]}" cy="{ys[2]}" r="{r * 0.8}" fill="{c["accent"]}"/>'
    else:  # the sample sits in the counter, between the two empty pips
        sample = f'<circle cx="{(xs[1] + xs[2]) / 2}" cy="{ys[3]}" r="{r * 0.9}" fill="{c["accent"]}"/>'
    rot = "" if small else ' transform="rotate(-6 32 32)"'
    return f'<g{rot}><rect x="5" y="5" width="54" height="54" rx="13" fill="{c["main"]}"/>{pips}{sample}</g>'


def mark_overlay(c, small):
    """A+D: the b drawn as overlaid posterior draws of the histogram; where they agree it is darkest."""
    base, x0, x1 = 58.0, 7.0, 57.0
    nb = 7 if small else 10
    w = (x1 - x0) / nb
    R, r = 17.0, 7.4
    cx, cy = x0 + w + (x1 - x0 - w) / 2, base - R
    # mean heights: the stem bin is tall, the others trace the bowl
    mean = []
    for k in range(nb):
        if k == 0:
            mean.append(base - 4)
            continue
        dx = x0 + (k + 0.5) * w - cx
        mean.append(R + math.sqrt(max(R * R - dx * dx, 0)) if abs(dx) < R else R * 0.5)
    mean = np.array(mean)
    rng = np.random.default_rng(3)
    nd, op = (3, 0.3) if small else (7, 0.17)
    mid = f"bmask{next(_ids)}"  # unique per drawing: the page repeats each mark
    paths = []
    for _ in range(nd):
        h = mean * np.exp(rng.normal(0, 0.15, nb))
        h[0] = min(h[0], base - 2)
        d = f"M{f(x0)} {f(base)}"
        for k in range(nb):
            d += f"V{f(base - h[k])}H{f(x0 + (k + 1) * w)}"
        paths.append(f'<path d="{d}V{f(base)}Z" fill="{c["main"]}" opacity="{op}"/>')
    d = f"M{f(x0)} {f(base)}"
    for k in range(nb):
        d += f"V{f(base - mean[k])}H{f(x0 + (k + 1) * w)}"
    outline = (
        f'<path d="{d}V{f(base)}" fill="none" stroke="{c["main"]}" stroke-width="{2.2 if small else 1.6}" '
        'stroke-linejoin="round"/>'
    )
    mask = (
        f'<mask id="{mid}"><rect width="64" height="64" fill="white"/>'
        f'<circle cx="{f(cx)}" cy="{f(cy)}" r="{r}" fill="black"/></mask>'
    )
    return (
        f"{mask}<g mask=\"url(#{mid})\">{''.join(paths)}{outline}</g>"
        f'<circle cx="{f(cx)}" cy="{f(cy)}" r="{3.6 if small else 3.2}" fill="{c["accent"]}"/>'
    )


