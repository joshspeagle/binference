def resolve(path: str) -> Any:
    """The object a dotted path names: the longest importable module, then attributes."""
    parts = path.split(".")
    for i in range(len(parts), 0, -1):
        try:
            obj = importlib.import_module(".".join(parts[:i]))
        except ImportError:
            continue
        for name in parts[i:]:
            obj = getattr(obj, name)
        return obj
    raise ImportError(path)


def fmt(value: Any) -> str:
    """A default as a reader would type it."""
    if isinstance(value, float):
        return format(value, "g")
    return repr(value)


def members(path: str, seen: set[type]) -> list[tuple[str, Any]]:
    """(where, callable) of a function, or of a class's constructor and public methods."""
    obj = resolve(path)
    if not inspect.isclass(obj):
        return [(path, obj)]
    out = [] if path in NO_CONSTRUCTOR else [(path, obj)]
    for cls in obj.__mro__:
        if cls is object or cls in seen or not cls.__module__.startswith("binference"):
            continue
        seen.add(cls)
        for name, attr in vars(cls).items():
            func = getattr(attr, "__func__", attr)
            if not name.startswith("_") and inspect.isfunction(func):
                out.append((f"{path}.{name}", func))
    return out


def defaults(func: Any) -> list[inspect.Parameter]:
    params = inspect.signature(func).parameters.values()
    return [p for p in params if p.default is not p.empty and p.name not in SKIP_PARAMS]


#: the end of a first sentence: a full stop (not of "e.g." or "i.e.") before a capital,
#: a backtick or the end
SENTENCE_END = re.compile(r"(?<!e\.g)(?<!i\.e)\.(?=\s+[A-Z`]|$)")


def descriptions(func: Any) -> dict[str, str]:
    """The first sentence of each parameter's numpydoc entry, by name, in MyST markup."""
    out = {}
    for p in NumpyDocString(inspect.getdoc(func) or "")["Parameters"]:
        text = " ".join(" ".join(p.desc).split())
        end = SENTENCE_END.search(text)
        text = text[: end.end()] if end else text
        # reStructuredText to MyST: ``code`` to `code`, :role:`x` to {role}`x`
        text = re.sub(r":(\w+):`", r"{\1}`", text.replace("``", "`"))
        for name in p.name.split(","):
            out[name.strip().lstrip("*")] = text
    return out


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def signature_tables() -> list[str]:
    lines, seen = [], set()
    for title, paths in SECTIONS:
        lines += [f"### {title}", "", "| Name | Default | Where | What it controls |"]
        lines.append("|---|---|---|---|")
        for path in paths:
            for where, func in members(path, seen):
                docs = descriptions(func)
                for p in defaults(func):
                    text = docs.get(p.name)
                    if not text:
                        raise ValueError(f"document {p.name} in the docstring of {where}")
                    lines.append(
                        f"| `{p.name}` | `{cell(fmt(p.default))}` | `{where}` | {cell(text)} |"
                    )
        lines.append("")
    return lines


def constant_tables() -> list[str]:
    lines = []
    for title, rows in CONSTANTS:
        lines += [f"### {title}", "", "| Name | Value | Where | What it controls |"]
        lines.append("|---|---|---|---|")
        for name, value, where, fragments, text in rows:
            obj = resolve(where)
            if fragments:
                # a constant's fragments are read in its module
                home = obj if callable(obj) else resolve(where.rsplit(".", 1)[0])
                source = inspect.getsource(home)
                missing = [f for f in fragments if f not in source]
                if missing:
                    raise ValueError(f"{where} no longer contains {missing}; update {__file__}")
                shown = value
            else:
                shown = f"`{cell(fmt(obj))}`"
            lines.append(f"| {name} | {cell(shown)} | `{where}` | {cell(text)} |")
        lines.append("")
    return lines


def covered() -> set[str]:
    """Paths of every public callable that has a default, to compare with SECTIONS."""
    found = set()
    for mod_name in (
        "binference",
        "binference.priors",
        "binference.samplers",
        "binference.diagnostics",
        "binference.simulate",
        "binference.validation",
        "binference.plotting",
        "binference.io",
    ):
        mod = importlib.import_module(mod_name)
        for name in mod.__all__:
            obj = getattr(mod, name)
            if not callable(obj) or (inspect.isclass(obj) and issubclass(obj, BaseException)):
                continue  # warning and error classes take no options
            path = f"{mod_name}.{name}"
            if any(defaults(f) for _, f in members(path, set())):
                found.add(path)
    return found


#: public callables with defaults that the page leaves out, and why
LEFT_OUT = {
    "binference.Summary": "a table that results build",
    "binference.priors.BoundPrior": "a prior bound to bins, built by the model",
    "binference.samplers.Engine": "the base class of the engines",
    "binference.simulate.Mock": "a container that the mocks return",
    "binference.simulate.Truth": "a container that the mocks return",
}


def render() -> str:
    """The generated block of the page."""
    listed = {p for _, paths in SECTIONS for p in paths}
    unlisted = covered() - listed - set(LEFT_OUT)
    if unlisted:
        raise ValueError(f"add {sorted(unlisted)} to SECTIONS or LEFT_OUT in {__file__}")
    body = ["## Public defaults", ""]
    body += signature_tables()
    body += ["## Run-time defaults and thresholds", ""]
    body += constant_tables()
    return "\n".join([BEGIN, "", *body, END])


def current() -> str:
    """The generated block as the page holds it."""
    text = PAGE.read_text(encoding="utf-8")
    start, end = text.index(BEGIN), text.index(END) + len(END)
    return text[start:end]


def main(argv: list[str]) -> int:
    new = render()
    if "--check" in argv:
        if current() != new:
            print(f"{PAGE} is stale: run python docs/_scripts/defaults_table.py")
            return 1
        return 0
    text = PAGE.read_text(encoding="utf-8")
    old = current()
    PAGE.write_text(text.replace(old, new), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
