"""Write the tables of docs/reference/defaults.md from the code.

Usage: python docs/_scripts/defaults_table.py [--check]

Every value in the tables is read from the code: signature defaults with
``inspect.signature``, named constants with ``getattr``. A parameter's description is
the first sentence of its entry in the numpydoc ``Parameters`` section of its
callable's docstring (a class's for its constructor). A run-time default or threshold
written as a literal inside a function is listed with the code fragment that sets it,
and the fragment must still appear in that function's source; the descriptions of
these live here. The script stops with an error on a public callable with defaults
that SECTIONS does not list, a defaulted parameter its docstring does not document,
or a fragment that no longer appears. ``--check`` exits with status 1 when the page
differs from what the script would write; ``tests/test_docs_reference.py`` runs the
same check.
"""

